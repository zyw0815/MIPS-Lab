.data
rs_string: .asciiz "B[i]= \n"  # 提示字符串，末尾带换行
nline: .asciiz "\n"        # 换行符，用于元素间换行
A: .word 4 6 12 -8 5   # 数组A：5个word，地址偏移0/4/8/12/16（对应A[0]-A[4]）
B: .word 3 2 1 4 0     # 数组B：初始值3/2/1/4/0，地址偏移0/4/8/12/16（对应B[0]-B[4]）

.text
.globl main
main:
 # 1. 打印提示字符串 "B[i]= "
 la $a0, rs_string 
 li $v0, 4
 syscall

 # 2. 加载数组A、B的起始地址，定义数组长度
 la $s0, A           # $s0 = 数组A的起始地址
 la $s1, B           # $s1 = 数组B的起始地址
 li $s2, 5           # $s2 = 数组B的长度（5个元素）

 # 3. 计算并更新B[0]的值
 lw $t0, 12($s0)     # 取A[3]：A的起始地址+12字节（3*4），值为-8
 lw $t1, 16($s1)     # 取B[4]：B的起始地址+16字节（4*4），值为0
 sll $t0, $t0, 1     # A[3] * 2：-8 << 1 = -16（左移1位等价于×2）
 add $t0, $t0, $t1   # 2*A[3] + B[4] = -16 + 0 = -16
 sw $t0, ($s1)       # 将-16存入B[0]（覆盖原初始值3）

# 4. 循环打印数组B的所有元素
loop:
 lw $a0, ($s1)       # 加载当前B的元素（初始为B[0]，后续逐步+4）
 li $v0, 1
 syscall             # 打印当前整数

 la $a0, nline       # 加载换行符地址
 li $v0, 4
 syscall             # 打印换行，实现元素分行

 addi $s2, $s2, -1   # 数组长度减1（剩余元素数）
 addi $s1, $s1, 4    # B的地址+4字节，指向下一个元素（word占4字节）
 bne $s2, $zero, loop # 剩余元素数≠0则继续循环

 # 5. 程序退出
 li $v0, 10
 syscall